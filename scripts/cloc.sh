#!/usr/bin/env bash
# Count lines in the source and docs we actually write.
#
# Included: the C core (and the Stronghold wrapper), the page (JS, CSS,
# HTML, and the help pages under ui/src/help), shell scripts, our tests,
# and Markdown (docs/ plus the root notes).
#
# Left out: the Tauri shell, vendored Unity, node_modules, lockfiles,
# Vite's cache, and build / dist / target trees.
#
# Extra arguments are passed through to cloc, before the tree root.
set -euo pipefail

root=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)
cd "$root"

if ! command -v cloc >/dev/null 2>&1; then
  printf 'cloc is not installed\n' >&2
  exit 1
fi

exec cloc \
  --fullpath \
  --stat \
  --unicode \
  --no-autogen \
  --hide-rate \
  --progress-rate=0 \
  --show-errors \
  --timeout=0 \
  --diff-timeout=0 \
  --max-file-size=50 \
  --skip-uniqueness \
  --skip-archive='(zip|tar(.(gz|Z|bz2|xz|7z))?|tgz|tbz2|txz|7z)' \
  --exclude-dir=node_modules,build,build-mini,dist,target,.git,.vite,framework,gen,autogenerated,deps,icons,CMakeFiles \
  --exclude-ext=png,ico,icns,gif,jpg,jpeg,webp,svg,lock,bin,o,a,so,dll,exe,pdb,wasm,map \
  --not-match-d='(^|/)src-tauri(/|$)' \
  --not-match-d='(^|/)node_modules(/|$)' \
  --not-match-d='(^|/)build(/|$)' \
  --not-match-d='(^|/)build-mini(/|$)' \
  --not-match-d='(^|/)dist(/|$)' \
  --not-match-d='(^|/)target(/|$)' \
  --not-match-d='(^|/)third_party(/|$)' \
  --not-match-d='(^|/)\.vite(/|$)' \
  --not-match-d='(^|/)\.git(/|$)' \
  --not-match-d='(^|/)tests/unity/framework(/|$)' \
  --not-match-d='(^|/)autogenerated(/|$)' \
  --not-match-d='(^|/)CMakeFiles(/|$)' \
  --not-match-f='(^|/)package-lock\.json$' \
  --not-match-f='(^|/)Cargo\.lock$' \
  --not-match-f='(^|/)PAVILLION_BUILD$' \
  --not-match-f='\.png$' \
  --not-match-f='\.gitignore$' \
  --not-match-f='\.gitattributes$' \
  --force-lang='Markdown,md' \
  --force-lang='YAML,yml' \
  --force-lang='CMake,cmake' \
  --force-lang='Bourne Shell,sh' \
  --force-lang='SQL,sql' \
  --script-lang='Bourne Shell,bash' \
  --script-lang='Bourne Shell,sh' \
  "$@" \
  .
